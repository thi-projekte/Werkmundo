-- Werkmundo / Offer-Service: initial persistence schema (Issue #32)
-- Schema prepared for the updated Offer-Service contract (2026-11-08).
-- Official offer numbers and VAT are deliberately deferred to their agreed contracts.

CREATE TABLE offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_key VARCHAR(255) NOT NULL UNIQUE,
    customer_id VARCHAR(255),
    craftsman_id VARCHAR(255),
    customer_access_token_hash VARCHAR(255),
    customer_access_token_expires_at TIMESTAMP WITHOUT TIME ZONE,
    estimated_work_duration_hours NUMERIC(19, 4),
    status VARCHAR(40) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX idx_offers_craftsman_id ON offers (craftsman_id);

CREATE TABLE offer_positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id BIGINT NOT NULL REFERENCES offers (id) ON DELETE CASCADE,
    type VARCHAR(20),
    name TEXT,
    description TEXT,
    manufacturer TEXT,
    quantity NUMERIC(19, 4) NOT NULL,
    unit VARCHAR(60),
    catalog_product_id VARCHAR(255),
    unit_price NUMERIC(19, 4) NOT NULL,
    position_order INTEGER NOT NULL
);

CREATE INDEX idx_offer_positions_order ON offer_positions (offer_id, position_order);

CREATE TABLE offer_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id BIGINT NOT NULL REFERENCES offers (id) ON DELETE CASCADE,
    status VARCHAR(40) NOT NULL,
    changed_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX idx_offer_status_history_order ON offer_status_history (offer_id, id);

CREATE TABLE offer_correction_suggestions (
    offer_id BIGINT NOT NULL REFERENCES offers (id) ON DELETE CASCADE,
    item_order INTEGER NOT NULL,
    suggestion TEXT NOT NULL,
    PRIMARY KEY (offer_id, item_order)
);

CREATE TABLE offer_customer_change_requests (
    offer_id BIGINT NOT NULL REFERENCES offers (id) ON DELETE CASCADE,
    item_order INTEGER NOT NULL,
    change_request TEXT NOT NULL,
    PRIMARY KEY (offer_id, item_order)
);
